class ProvinceData {
  const ProvinceData({
    required this.name,
    required this.shortName,
    required this.tagline,
    required this.sites,
    required this.color,
    required this.points,
    required this.label,
    this.islands = const [],
    this.cutouts = const [],
  });

  final String name, shortName, tagline;
  final List<String> sites;
  final Color color;
  final List<Offset> points;
  final Offset label;
  final List<List<Offset>> islands;
  final List<List<Offset>> cutouts;
}

// Each edge includes its two junctions. Adjacent regions reuse the edge in
// reverse order instead of independently approximating their common border.
List<Offset> _outline(List<Iterable<Offset>> edges) {
  final points = <Offset>[];
  for (final edge in edges) {
    for (final point in edge) {
      if (points.isEmpty || points.last != point) points.add(point);
    }
  }
  if (points.length > 1 && points.first == points.last) points.removeLast();
  return List<Offset>.unmodifiable(points);
}

